const gridElement = document.getElementById('crossword-grid');
const acrossCluesElement = document.getElementById('across-clues');
const downCluesElement = document.getElementById('down-clues');

let currentDirection = 'across';
let activeCell = null;
let cellInputs = [];

function initPuzzle() {
    gridElement.innerHTML = '';
    acrossCluesElement.innerHTML = '';
    downCluesElement.innerHTML = '';
    activeCell = null;
    cellInputs = [];
    
    gridElement.style.gridTemplateColumns = `repeat(${puzzle.width}, 1fr)`;
    gridElement.style.gridTemplateRows = `repeat(${puzzle.height}, 1fr)`;

    for (let r = 0; r < puzzle.height; r++) {
        cellInputs[r] = [];
        for (let c = 0; c < puzzle.width; c++) {
            const cellVal = puzzle.cells[r][c];
            const cellDiv = document.createElement('div');
            cellDiv.className = 'crossword-cell';
            
            if (cellVal === '.') {
                cellDiv.classList.add('block');
                cellInputs[r][c] = null;
            } else {
                const number = puzzle.numbers[r][c];
                if (number > 0) {
                    const numSpan = document.createElement('span');
                    numSpan.className = 'cell-number';
                    numSpan.textContent = number;
                    cellDiv.appendChild(numSpan);
                }

                const input = document.createElement('input');
                input.type = 'text';
                input.maxLength = 1;
                input.dataset.row = r;
                input.dataset.col = c;
                
                input.addEventListener('focus', () => handleFocus(r, c));
                input.addEventListener('input', (e) => handleInput(e, r, c));
                input.addEventListener('keydown', (e) => handleKeydown(e, r, c));
                
                cellDiv.appendChild(input);
                cellInputs[r][c] = input;
            }
            gridElement.appendChild(cellDiv);
        }
    }

    renderClues(puzzle.acrossClues, acrossCluesElement, 'across');
    renderClues(puzzle.downClues, downCluesElement, 'down');
}

function renderClues(clues, container, direction) {
    clues.forEach(clue => {
        const li = document.createElement('li');
        li.className = 'clue-item';
        li.dataset.number = clue.number;
        li.dataset.direction = direction;
        li.innerHTML = `<span class="clue-number">${clue.number}.</span> ${clue.text}`;
        
        li.addEventListener('click', () => {
            currentDirection = direction;
            if (cellInputs[clue.row][clue.col]) {
                cellInputs[clue.row][clue.col].focus();
            }
        });
        
        container.appendChild(li);
    });
}

function handleFocus(r, c) {
    if (activeCell && activeCell.row === r && activeCell.col === c) {
        currentDirection = currentDirection === 'across' ? 'down' : 'across';
    } else {
        activeCell = { row: r, col: c };
    }
    highlightWord(r, c);
}

function handleInput(e, r, c) {
    const val = e.target.value.toUpperCase();
    e.target.value = val;
    if (val) moveToNext(r, c);
}

function handleKeydown(e, r, c) {
    if (e.key === 'Backspace' && !e.target.value) {
        moveToPrev(r, c);
    } else if (e.key === 'ArrowRight') {
        currentDirection = 'across';
        moveToNext(r, c, true);
    } else if (e.key === 'ArrowLeft') {
        currentDirection = 'across';
        moveToPrev(r, c, true);
    } else if (e.key === 'ArrowDown') {
        currentDirection = 'down';
        moveToNext(r, c, true);
    } else if (e.key === 'ArrowUp') {
        currentDirection = 'down';
        moveToPrev(r, c, true);
    }
}

function moveToNext(r, c, force = false) {
    let nextR = r;
    let nextC = c;
    if (currentDirection === 'across') nextC++;
    else nextR++;
    if (nextR < puzzle.height && nextC < puzzle.width && cellInputs[nextR][nextC]) {
        cellInputs[nextR][nextC].focus();
    }
}

function moveToPrev(r, c, force = false) {
    let prevR = r;
    let prevC = c;
    if (currentDirection === 'across') prevC--;
    else prevR--;
    if (prevR >= 0 && prevC >= 0 && cellInputs[prevR][prevC]) {
        cellInputs[prevR][prevC].focus();
    }
}

function highlightWord(r, c) {
    document.querySelectorAll('.crossword-cell').forEach(cell => cell.classList.remove('highlight', 'focus'));
    document.querySelectorAll('.clue-item').forEach(item => item.classList.remove('active'));
    if (!cellInputs[r][c]) return;

    cellInputs[r][c].parentElement.classList.add('focus');
    let startR = r, startC = c;
    let clueNumber = -1;

    if (currentDirection === 'across') {
        while (startC > 0 && cellInputs[r][startC - 1]) startC--;
        let currC = startC;
        while (currC < puzzle.width && cellInputs[r][currC]) {
            if (currC !== c) cellInputs[r][currC].parentElement.classList.add('highlight');
            currC++;
        }
        clueNumber = puzzle.numbers[r][startC];
        if(clueNumber > 0) highlightClue(clueNumber, 'across');
    } else {
        while (startR > 0 && cellInputs[startR - 1][c]) startR--;
        let currR = startR;
        while (currR < puzzle.height && cellInputs[currR][c]) {
            if (currR !== r) cellInputs[currR][c].parentElement.classList.add('highlight');
            currR++;
        }
        clueNumber = puzzle.numbers[startR][c];
        if(clueNumber > 0) highlightClue(clueNumber, 'down');
    }
}

function highlightClue(number, direction) {
    const clueItem = document.querySelector(`.clue-item[data-number="${number}"][data-direction="${direction}"]`);
    if (clueItem) {
        clueItem.classList.add('active');
        if (window.innerWidth > 768) {
            clueItem.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
        }
    }
}

document.addEventListener('DOMContentLoaded', () => {
    initPuzzle();
});
